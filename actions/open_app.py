# URI targets the alias table itself names (e.g. "ms-settings:"). Only these
# are ever handed to the shell's URI handler — never a string the model made up,
# which could name any registered protocol handler on the machine.
_TRUSTED_URIS = {v for m in _APP_ALIASES.values() for v in m.values() if v.endswith(":")}

# What the Start-menu / Spotlight typing fallback is allowed to type. The search
# box also RUNS commands ("cmd /c ..."), so anything beyond a plain app name is
# refused rather than typed.
_PLAIN_NAME_RE = re.compile(r"^[\w .+-]{1,60}$")


def _normalize(raw: str) -> str:
    key = raw.lower().strip()

    if key in _APP_ALIASES:
        return _APP_ALIASES[key].get(_SYSTEM, raw)

    # Whole-word match only, longest alias first: "open chrome please" finds
    # chrome, but "digital" no longer finds "git" and one letter finds nothing.
    for alias_key in sorted(_APP_ALIASES, key=len, reverse=True):
        if re.search(rf"\b{re.escape(alias_key)}\b", key):
            return _APP_ALIASES[alias_key].get(_SYSTEM, raw)

    return raw


def _split_alias(app_name: str) -> tuple[str, list[str]]:
    """Alias values may carry arguments ("libreoffice --writer"); user-supplied
    names never do — a name that is not an alias value is one executable."""
    if any(app_name in m.values() for m in _APP_ALIASES.values()) and " --" in app_name:
        parts = shlex.split(app_name)
        return parts[0], parts[1:]
    return app_name, []


def _typing_fallback(app_name: str, open_keys: tuple[str, ...], settle: float):
    """Types the name into the OS launcher. Returns None (= unconfirmed): it
    cannot tell whether anything actually opened."""
    if not _PLAIN_NAME_RE.match(app_name):
        print(f"[open_app] Refusing to type a non-plain name into the launcher: {app_name!r}")
        return False
    try:
        import pyautogui
        pyautogui.PAUSE = 0.1
        pyautogui.hotkey(*open_keys) if len(open_keys) > 1 else pyautogui.press(open_keys[0])
        time.sleep(0.7)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.9)
        pyautogui.press("enter")
        time.sleep(settle)
        return None
    except Exception as e:
        print(f"[open_app] Launcher search failed: {e}")
        return False


def _launch_windows(app_name: str):

    exe, args = _split_alias(app_name)
    binary = shutil.which(exe) or shutil.which(exe.split(".")[0])
    if binary:
        try:
            # Resolved path + argument list, never shell=True: the name comes
            # from the model, and "notepad.exe & <anything>" used to pass the
            # which() check and run the rest through cmd.
            subprocess.Popen(
                [binary, *args],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            time.sleep(1.5)
            return True
        except Exception as e:
            print(f"[open_app] subprocess failed: {e}")

    if app_name in _TRUSTED_URIS:
        try:
            os.startfile(app_name)
            time.sleep(1.0)
            return True
        except Exception:
            pass

    return _typing_fallback(app_name, ("win",), 2.5)


def _launch_macos(app_name: str):

    try:
        result = subprocess.run(
            ["open", "-a", app_name],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    try:
        result = subprocess.run(
            ["open", "-a", f"{app_name}.app"],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    binary = shutil.which(app_name) or shutil.which(app_name.lower())
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    return _typing_fallback(app_name, ("command", "space"), 1.5)


_LINUX_TERMINAL_FALLBACKS = [
    "x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal",
    "xterm", "lxterminal", "mate-terminal", "tilix", "alacritty", "kitty",
]

def _launch_linux(app_name: str):

    # terminal emulators: try common ones in order
    if app_name in ("x-terminal-emulator", "gnome-terminal", "terminal"):
        for term in _LINUX_TERMINAL_FALLBACKS:
            if shutil.which(term):
                try:
                    subprocess.Popen([term], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    time.sleep(1.0)
                    return True
                except Exception:
                    continue

    exe, args = _split_alias(app_name)
    binary = (
        shutil.which(exe) or
        shutil.which(exe.lower()) or
        shutil.which(exe.lower().replace(" ", "-")) or
        shutil.which(exe.lower().replace(" ", "_"))
    )
    if binary:
        try:
            subprocess.Popen(
                [binary, *args],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    for desktop_name in [
        app_name.lower(),
        app_name.lower().replace(" ", "-"),
        app_name.lower().replace(" ", ""),
    ]:
        try:
            result = subprocess.run(
                ["gtk-launch", desktop_name],
                capture_output=True, timeout=5
            )
            if result.returncode == 0:
                return True
        except Exception:
            pass

    return False


_OS_LAUNCHERS = {
    "Windows": _launch_windows,
    "Darwin":  _launch_macos,
    "Linux":   _launch_linux,
}

def open_app(
    parameters=None,
    response=None,
    player=None,
    session_memory=None,
) -> str:
    app_name = (parameters or {}).get("app_name", "").strip()

    if not app_name:
        return "No application name provided."

    launcher = _OS_LAUNCHERS.get(_SYSTEM)
    if launcher is None:
        return f"Unsupported operating system: {_SYSTEM}"

    normalized = _normalize(app_name)
    print(f"[open_app] Launching: '{app_name}' → '{normalized}' ({_SYSTEM})")

    if player:
        player.write_log(f"[open_app] {app_name}")

    try:
        ok = launcher(normalized)
        if ok is False and normalized.lower() != app_name.lower():
            ok = launcher(app_name)
        if ok:
            return f"Opened {app_name}."
        if ok is None:
            return (f"I searched for {app_name} in the system launcher, but I "
                    f"cannot confirm it opened.")
        return (
            f"Could not confirm that {app_name} launched. "
            f"It may still be loading, or it might not be installed."
        )
    except Exception as e:
        print(f"[open_app] Error: {e}")
        return f"Failed to open {app_name}: {e}"


